#!/usr/bin/env python3
"""Validate course lab entry points and emit local, file://-compatible metadata."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_catalog():
    data = json.loads((ROOT / "content/visual-labs.json").read_text())
    seen = set()
    for lab in data["labs"]:
        assert lab["id"] not in seen, lab["id"]
        seen.add(lab["id"])
        assert lab["file"] in {"visual_labs.html", "object_lifetime_demo.html"}
        assert len(set(lab["scenarios"])) == len(lab["scenarios"])
        for entry in lab["entries"]:
            station = json.loads((ROOT / ("content/" + entry["station"] + ".json")).read_text())
            assert any(s["id"] == entry["section"] for s in station["theory"]), entry
            assert entry["scenario"] in lab["scenarios"], entry
            entry["file"] = station["meta"]["sourceFile"]
    return data


def render():
    data = json.dumps(load_catalog()["labs"], ensure_ascii=False, indent=2)
    return "// Generated by tools/build_visual_labs.py.\nwindow.COURSE_LABS = " + data + ";\n" + '''window.courseLabHref = function(id, scenario, station, section) {
  var lab = window.COURSE_LABS.find(function(item) { return item.id === id; });
  if (!lab || lab.scenarios.indexOf(scenario) < 0) return "visual_labs.html";
  var context = station ? "&from=" + encodeURIComponent(station) + "&section=" + encodeURIComponent(section || "") : "";
  if (id === "lifetime") {
    var level = station === "station0" ? "basics" : station === "station2" ? "inheritance" : "all";
    return lab.file + "?level=" + level + context + "#" + encodeURIComponent(scenario);
  }
  return lab.file + "#lab=" + encodeURIComponent(id) + "&scenario=" + encodeURIComponent(scenario) + context;
};
'''


if __name__ == "__main__":
    (ROOT / "generated/visual-labs.data.js").write_text(render())
    print("Built course lab catalog")
