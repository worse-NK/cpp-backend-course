#!/usr/bin/env python3
"""One reviewed term catalog feeds both small definition cards and a static glossary."""
import json
import hashlib
from html import escape
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
GROUPS = ('C++', 'Инструменты', 'Многопоточность', 'Сети', 'API', 'Данные', 'Эксплуатация')


def catalog_version():
    return hashlib.sha256((ROOT / 'content/glossary.json').read_bytes()).hexdigest()[:12]


def load():
    data = json.loads((ROOT / 'content/glossary.json').read_text())
    assert data['version'] == 1
    seen, forms = set(), {}
    for e in data['entries']:
        assert re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', e['id']) and e['id'] not in seen, e['id']
        seen.add(e['id'])
        assert e['group'] in GROUPS
        assert 20 <= len(e['short']) <= 240, e['id']
        assert len(e['paragraphs']) >= 2 and all(len(p) >= 50 for p in e['paragraphs']), e['id']
        assert e['forms'] and all(f.strip() for f in e['forms'])
        for form in e['forms']:
            folded = form.casefold()
            assert folded not in forms or forms[folded] == e['id'], form
            forms[folded] = e['id']
        for definition in e['inlineDefinitions']:
            assert definition and '(' not in definition[:1]
        learn = e['learn']
        station = json.loads((ROOT / ('content/' + learn['station'] + '.json')).read_text())
        assert station['meta']['sourceFile'] == learn['file']
        assert any(s['id'] == learn['section'] for s in station['theory']), e['id']
        assert e['sources'], e['id'] + ': at least one primary source is required'
        for source in e['sources']:
            assert source['title'] and urlsplit(source['url']).scheme == 'https', e['id']
    return data['entries']


def render_data():
    compact = [{k: e[k] for k in ('id', 'title', 'forms', 'short', 'inlineDefinitions')} for e in load()]
    return '// Generated by tools/build_glossary.py.\nwindow.COURSE_TERMS = ' + json.dumps(compact, ensure_ascii=False, indent=2).replace('</', '<\\/') + ';\n'


def render():
    entries = load()
    counts = {g: sum(e['group'] == g for e in entries) for g in GROUPS}
    buttons = ''.join(f'<button type="button" data-group="{escape(g)}" aria-pressed="false">{escape(g)}<span>{counts[g]}</span></button>' for g in GROUPS)
    articles = []
    for e in sorted(entries, key=lambda e: e['title'].casefold()):
        title, eid = escape(e['title']), escape(e['id'])
        paragraphs = ''.join(f'<p>{escape(p)}</p>' for p in e['paragraphs'])
        learn = e['learn']
        href = escape(learn['file'] + '#section=' + learn['section'])
        sources = ' · '.join(f'<a href="{escape(s["url"])}" target="_blank" rel="noopener noreferrer">{escape(s["title"])} ↗</a>' for s in e['sources'])
        articles.append(f'''<article class="glossary-entry" id="term-{eid}" tabindex="-1" data-group="{escape(e['group'])}" data-aliases="{escape(' '.join(e['forms']))}">
<p class="entry-group">{escape(e['group'])}</p>
<h2><a href="#term-{eid}" title="Ссылка на этот термин">{title}<span aria-hidden="true">#</span></a></h2>
<p class="entry-short">{escape(e['short'])}</p>
<div class="entry-detail">{paragraphs}</div>
<a class="entry-lesson" href="{href}">Разобрать в учебнике: {escape(learn['label'])} →</a>
<details class="entry-sources"><summary>Первоисточники</summary><p>{sources}</p></details>
</article>''')
    return f'''<!doctype html>
<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="Понятные определения терминов курса C++ и backend: кратко, подробнее, с примерами и ссылками на главы и первоисточники.">
<title>Глоссарий · C++ и backend</title><link rel="stylesheet" href="assets/glossary.css"></head>
<body id="top"><a class="glossary-skip" href="#terms">К определениям</a>
<header class="glossary-top"><a class="glossary-brand" href="cpp_backend_roadmap.html">C++ <span>/ BACKEND</span></a><nav aria-label="Материалы курса"><a href="cpp_backend_roadmap.html">Курс</a><a href="cpp_cheatsheet.html">Шпаргалка</a><a href="sources.html">Источники</a></nav></header>
<div class="glossary-layout"><aside class="glossary-controls" aria-label="Поиск и темы">
<p class="glossary-eyebrow">СЛОВАРЬ КУРСА</p><h1>Понять термин.<br>Вернуться к смыслу.</h1>
<p class="glossary-intro">Короткое определение помогает не потерять нить чтения. Здесь — объяснение подробнее: как понятие работает, с чем его не путать и где разобрать в учебнике.</p>
<div class="glossary-search" hidden><label for="term-search">Найти термин</label><div><input id="term-search" type="search" placeholder="Инвариант, RAII, DNS…" autocomplete="off"><button id="term-search-clear" type="button" aria-label="Очистить поиск">×</button></div>
<nav class="glossary-groups" aria-label="Темы глоссария"><button type="button" data-group="" aria-pressed="true">Все понятия<span>{len(entries)}</span></button>{buttons}</nav></div>
<p id="term-count" role="status" aria-live="polite">{len(entries)} понятий · станции 0–10</p>
<p class="glossary-note">В главах термины с пунктиром открываются по нажатию. Подробное объяснение — в отдельной вкладке: позиция чтения и попытка теста сохраняются на прежней странице.</p></aside>
<main id="terms"><p class="glossary-empty" id="term-empty" hidden>Совпадений нет. Попробуй короткую часть слова, русское название или английское сокращение.</p>{''.join(articles)}</main></div>
<footer class="glossary-footer"><a href="#top">К началу ↑</a><a href="cpp_backend_roadmap.html">Вернуться к курсу →</a><p>Определения служат опорой для чтения, а не заменой учебной главы. Основная версия C++ — C++20; серверная глава о данных использует PostgreSQL 18.</p></footer>
<script src="assets/glossary.js" defer></script></body></html>'''


if __name__ == '__main__':
    (ROOT / 'generated/terms.data.js').write_text(render_data())
    (ROOT / 'glossary.html').write_text(render())
    print(f'Built glossary: {len(load())} concepts')
