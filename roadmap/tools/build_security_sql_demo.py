"""Bundle the standalone prototype's local SQLite engine for file:// and HTTP.

This does not edit station metadata, publish files, download dependencies or run
SQL. sql.js 1.13.0 MIT license remains in roadmap/vendor/sqljs/LICENSE.
"""
import hashlib
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR_SHA256 = "c83beac167ae9c1af075449555b1db68b24b5280d0fc65c1f7ac4d1cd103459d"


def render():
    vendor = ROOT / "vendor/sqljs/sql-asm.js"
    if hashlib.sha256(vendor.read_bytes()).hexdigest() != VENDOR_SHA256:
        raise ValueError("Expected the existing unmodified sql.js 1.13.0 asm build")
    sources = (vendor, ROOT / "assets/security-sql-model.js", ROOT / "assets/security-sql-worker.js")
    source = "\n;\n".join(path.read_text(encoding="utf-8") for path in sources)
    return ("// Generated by tools/build_security_sql_demo.py; sql.js MIT: vendor/sqljs/LICENSE.\n"
            "window.SECURITY_SQL_WORKER_SOURCE = " + json.dumps(source, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the committed bundle without writing it")
    args = parser.parse_args()
    target = ROOT / "generated/security-sql-worker.data.js"
    expected = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            raise SystemExit("Security SQL bundle is missing or stale; run tools/build_security_sql_demo.py")
        print("PASS: standalone security SQL bundle matches its local sources")
    else:
        target.write_text(expected, encoding="utf-8")
        print("Built standalone, local-only security SQL worker bundle")
