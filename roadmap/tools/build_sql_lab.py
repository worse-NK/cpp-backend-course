"""Embed worker source in a local classic script: no fetch/WASM/file:// CORS."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render():
    files=['vendor/sqljs/sql-asm.js','assets/sql-lab-core.js','assets/sql-lab-worker.js']
    source='\n;\n'.join((ROOT/f).read_text() for f in files)
    return '// Generated by tools/build_sql_lab.py; sql.js MIT license in vendor/sqljs/LICENSE.\nwindow.SQL_LAB_WORKER_SOURCE = '+json.dumps(source,ensure_ascii=False)+';\n'
if __name__=='__main__':
    (ROOT/'generated/sql-lab-worker.data.js').write_text(render())
    print('Built offline SQL worker bundle')
